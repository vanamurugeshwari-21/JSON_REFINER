import gradio as gr
import json
import re
from datetime import datetime
from enum import Enum
from typing import Dict, List, Any, Tuple
from collections import deque
from jsonschema import validate, ValidationError

# ============================================================
# JSON REFINER CORE ENGINE
# ============================================================

class CaseStyle(Enum):
    SNAKE_CASE = "snake_case"
    CAMEL_CASE = "camelCase"
    KEBAB_CASE = "kebab-case"
    PASCAL_CASE = "PascalCase"


class JSONRefinerCore:

    # ------------------------------
    # CASE CONVERSION
    # ------------------------------

    @staticmethod
    def to_snake_case(text: str) -> str:
        text = re.sub(r'[\s\-]+', '_', text)
        text = re.sub(r'([a-z])([A-Z])', r'\1_\2', text)
        text = re.sub(r'[^a-zA-Z0-9_]', '', text)
        return text.lower()

    @staticmethod
    def to_camel_case(text: str) -> str:
        snake = JSONRefinerCore.to_snake_case(text)
        parts = snake.split('_')
        return parts[0] + ''.join(word.capitalize() for word in parts[1:])

    @staticmethod
    def to_kebab_case(text: str) -> str:
        snake = JSONRefinerCore.to_snake_case(text)
        return snake.replace("_", "-")

    @staticmethod
    def to_pascal_case(text: str) -> str:
        camel = JSONRefinerCore.to_camel_case(text)
        return camel[0].upper() + camel[1:] if camel else ""

    @staticmethod
    def normalize_key(key: str, case_style: CaseStyle):
        key = key.strip()

        if case_style == CaseStyle.SNAKE_CASE:
            return JSONRefinerCore.to_snake_case(key)

        if case_style == CaseStyle.CAMEL_CASE:
            return JSONRefinerCore.to_camel_case(key)

        if case_style == CaseStyle.KEBAB_CASE:
            return JSONRefinerCore.to_kebab_case(key)

        if case_style == CaseStyle.PASCAL_CASE:
            return JSONRefinerCore.to_pascal_case(key)

        return key

    # ------------------------------
    # TYPE INFERENCE
    # ------------------------------

    @staticmethod
    def infer_type(value: str):

        value = value.strip()

        if value.lower() in ["null", "none", "nil", "undefined"]:
            return None

        if value.lower() in ["true", "yes", "on"]:
            return True

        if value.lower() in ["false", "no", "off"]:
            return False

        try:
            if "." not in value:
                return int(value)
        except:
            pass

        try:
            return float(value)
        except:
            pass

        if value.startswith("[") and value.endswith("]"):
            try:
                return json.loads(value)
            except:
                pass

        if value.startswith("{") and value.endswith("}"):
            try:
                return json.loads(value)
            except:
                pass

        return value

    # ------------------------------
    # KEY VALUE PARSER
    # ------------------------------

    @staticmethod
    def parse_key_value_text(text: str, case_style: CaseStyle):

        result = {}
        errors = []

        lines = text.split("\n")

        for i, line in enumerate(lines, 1):

            line = line.strip()

            if not line or line.startswith("#"):
                continue

            if ":" not in line:
                errors.append(f"Line {i}: Missing ':' separator")
                continue

            key, value = line.split(":", 1)

            key = key.strip()
            value = value.strip()

            if not key:
                errors.append(f"Line {i}: Empty key")
                continue

            normalized = JSONRefinerCore.normalize_key(key, case_style)

            converted_value = JSONRefinerCore.infer_type(value)

            if normalized in result:
                errors.append(f"Duplicate key '{normalized}' overwritten")

            result[normalized] = converted_value

        return result, errors

    # ------------------------------
    # JSON FLATTEN
    # ------------------------------

    @staticmethod
    def flatten_json(data: Dict, parent_key="", sep="."):

        items = []

        for k, v in data.items():

            new_key = f"{parent_key}{sep}{k}" if parent_key else k

            if isinstance(v, dict):
                items.extend(
                    JSONRefinerCore.flatten_json(v, new_key, sep).items()
                )

            elif isinstance(v, list):

                for i, item in enumerate(v):

                    if isinstance(item, dict):
                        items.extend(
                            JSONRefinerCore.flatten_json(
                                item, f"{new_key}.{i}", sep
                            ).items()
                        )
                    else:
                        items.append((f"{new_key}.{i}", item))

            else:
                items.append((new_key, v))

        return dict(items)

    # ------------------------------
    # UNFLATTEN
    # ------------------------------

    @staticmethod
    def unflatten_json(data: Dict, sep="."):

        result = {}

        for key, value in data.items():

            parts = key.split(sep)

            current = result

            for part in parts[:-1]:

                if part not in current:
                    current[part] = {}

                current = current[part]

            current[parts[-1]] = value

        return result

    # ------------------------------
    # MERGE JSON
    # ------------------------------

    @staticmethod
    def merge_json_objects(*objects):

        result = {}

        for obj in objects:

            for k, v in obj.items():

                if (
                    k in result
                    and isinstance(result[k], dict)
                    and isinstance(v, dict)
                ):
                    result[k] = JSONRefinerCore.merge_json_objects(result[k], v)

                else:
                    result[k] = v

        return result

    # ------------------------------
    # REMOVE NULLS
    # ------------------------------

    @staticmethod
    def remove_null_values(data: Dict):

        result = {}

        for k, v in data.items():

            if v is None:
                continue

            if isinstance(v, dict):
                result[k] = JSONRefinerCore.remove_null_values(v)
            else:
                result[k] = v

        return result

    # ------------------------------
    # JSON STATS
    # ------------------------------

    @staticmethod
    def get_json_stats(data: Dict):

        def count(obj):

            if isinstance(obj, dict):
                total = len(obj)
                nested = 0

                for v in obj.values():
                    c, n = count(v)
                    nested += c + n

                return total, nested

            if isinstance(obj, list):
                total = len(obj)
                nested = 0

                for item in obj:
                    c, n = count(item)
                    nested += c + n

                return total, nested

            return 0, 0

        top, nested = count(data)

        return {
            "top_level_keys": top,
            "total_keys": top + nested,
            "has_nested": any(isinstance(v, dict) for v in data.values()),
            "has_arrays": any(isinstance(v, list) for v in data.values()),
            "value_types": list(set(type(v).__name__ for v in data.values())),
        }


