def refine_json(text, case_style, remove_nulls, flatten, pretty):

    if not text.strip():
        return "", "❌ Empty input", ""

    case_enum = CaseStyle(case_style)

    data, errors = refiner.parse_key_value_text(text, case_enum)

    if remove_nulls:
        data = refiner.remove_null_values(data)

    if flatten:
        data = refiner.flatten_json(data)

    if pretty:
        output = json.dumps(data, indent=2)
    else:
        output = json.dumps(data)

    stats = refiner.get_json_stats(data)

    stats_text = f"""
Top Level Keys: {stats['top_level_keys']}
Total Keys: {stats['total_keys']}
Has Nested: {stats['has_nested']}
Has Arrays: {stats['has_arrays']}
Types: {', '.join(stats['value_types'])}
"""

    history.append(
        {
            "time": datetime.now().isoformat(),
            "input": text,
            "output": output,
        }
    )

    status = "✅ JSON generated"

    if errors:
        status += "\nWarnings:\n" + "\n".join(errors)

    return output, status, stats_text


def validate_json(json_text, schema_text, required):

    try:

        data = json.loads(json_text)

        messages = []

        if required.strip():

            fields = [f.strip() for f in required.split(",")]

            missing = [f for f in fields if f not in data]

            if missing:
                messages.append("Missing: " + ", ".join(missing))
            else:
                messages.append("Required fields OK")

        if schema_text.strip():

            schema = json.loads(schema_text)

            try:
                validate(data, schema)
                messages.append("Schema valid")

            except ValidationError as e:
                messages.append(str(e))

        if not messages:
            messages.append("Valid JSON")

        return "\n".join(messages), "Validation done"

    except Exception as e:
        return str(e), "Validation error"


def convert_case(json_text, target):

    try:

        data = json.loads(json_text)

        case_enum = CaseStyle(target)

        def convert(obj):

            if isinstance(obj, dict):
                return {
                    refiner.normalize_key(k, case_enum): convert(v)
                    for k, v in obj.items()
                }

            if isinstance(obj, list):
                return [convert(i) for i in obj]

            return obj

        result = convert(data)

        return json.dumps(result, indent=2), "Converted"

    except Exception as e:
        return "", str(e)


